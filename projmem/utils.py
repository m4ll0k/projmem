# File extensions that are PURE documentation / prose. The contract
# extractor's regex patterns (`--flag`, `process.env.X`) match
# documentation chatter and create false-positive contracts when run on
# these. We MUST skip them. See audit P0 (`projmem complete` flagged
# every flag mention in AGENTS.md as an "open obligation").
DOC_ONLY_EXTENSIONS = {
    ".md", ".markdown", ".txt", ".rst", ".adoc", ".asciidoc", ".org",
    ".rtf",
}


def is_doc_only(path: str) -> bool:
    """True iff the path's extension is documentation-only (no
    contract extraction)."""
    if not path:
        return False
    ext = os.path.splitext(path)[1].lower()
    return ext in DOC_ONLY_EXTENSIONS


